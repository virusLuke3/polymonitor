def trusted_hls_items(*, generated_at: str) -> List[Dict[str, Any]]:
    output: List[Dict[str, Any]] = []
    for source in TRUSTED_HLS_SOURCES:
        item = dict(source)
        item.update(
            {
                "sourceRole": item.get("sourceRole") or "channel",
                "sourceType": "hls",
                "sourceName": item.get("sourceName") or "worldmonitor-trusted-hls",
                "sourceUrl": item.get("sourceUrl") or item.get("hlsUrl"),
                "quality": item.get("quality") or "trusted",
                "status": item.get("status") or "ready",
                "availability": item.get("availability") or "public",
                "matchedTerms": item.get("matchedTerms") or list(item.get("marketTags") or [])[:4],
                "lastCheckedAt": generated_at,
                "playbackTier": "trusted-hls",
                "playbackStrategy": "proxied-hls" if item.get("hlsProxyRequired") else "direct-hls",
            }
        )
        output.append(item)
    return output


def trusted_hls_urls() -> Iterable[str]:
    for source in TRUSTED_HLS_SOURCES:
        url = str(source.get("hlsUrl") or "").strip()
        if url:
            yield url
